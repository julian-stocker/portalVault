/** Der Rumpf der Sicht, wie `0146` ihn definiert — extrahiert, nicht getippt. */
function sichtRumpfAus(pfad: string, marke: string): string {
  const t = datei(pfad);
  const a = t.indexOf(marke);
  expect(a, `${marke} fehlt in ${pfad}`).toBeGreaterThan(-1);
  return t.slice(a + marke.length, t.indexOf(";", a));
}

describe("0151 — es gibt genau EINE Definition der Kaufbarkeit", () => {
  it("der Rumpf in 0151 ist zeichengleich mit dem in 0146", () => {
    /*
     * DIE WICHTIGSTE PRÜFUNG DIESES BLOCKS. `0146` bleibt nach Entscheidung
     * E-3 die verbindliche Referenz; `0151` übernimmt sie und stellt nichts
     * Zweites auf. Liefen die beiden auseinander, hätte dieses Projekt zwei
     * Antworten auf „ist diese Figur kaufbar" — und die Benachrichtigung
     * stünde auf der anderen als der Shop.
     */
    const aus146 = sichtRumpfAus("supabase/migrations/0146_offer_state.sql",
                                 "create view public.offer_state_live as");
    const a = migration151.indexOf("v_rumpf text := $sicht$");
    expect(a, "das Rumpf-Literal fehlt in 0151").toBeGreaterThan(-1);
    const b = migration151.indexOf("$sicht$;", a);
    const aus151 = migration151.slice(a + "v_rumpf text := $sicht$".length, b);
    expect(aus151).toBe(aus146);
  });

  it("und das Literal kommt genau EINMAL vor — es wird zweimal BENUTZT", () => {
    /* Zum Anlegen (`create view … as` || v_rumpf) und als Unterabfrage beim
       Vergleichen in Stufe 4. Eine zweite Textfassung wäre genau das, was
       E-3 ausschließt. */
    expect([...migration151.matchAll(/min\(round\(o\.price \* 100\)\)/g)]).toHaveLength(1);
    /* Gezählt wird im AUSFÜHRBAREN Teil: der Kopfkommentar nennt
       `|| v_rumpf` ebenfalls, wenn er die zwei Verwendungen erklärt. */
    const ausfuehrbar151 = migration151
      .replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*--.*$/gm, "");
    expect([...ausfuehrbar151.matchAll(/\|\| v_rumpf/g)]).toHaveLength(2);
  });

  it("der Kommentar ist ebenfalls zeichengleich aus 0146", () => {
    const aus146 = sichtRumpfAus("supabase/migrations/0146_offer_state.sql",
                                 "comment on view public.offer_state_live is").trim();
    expect(migration151).toContain(`quote_literal(${aus146})`);
  });

  it("`create or replace view` kommt im ausführbaren Teil NICHT vor", () => {
    /* Es wäre der kurze und gleichzeitig der gefährliche Weg: auf Staging
       würde es einen bestehenden Rumpf stillschweigend ersetzen. */
    const ohneKommentar = migration151
      .replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*--.*$/gm, "");
    expect(ohneKommentar).not.toContain("create or replace view");
    expect(ohneKommentar).toContain("'create view public.offer_state_live as' || v_rumpf");
  });
});

describe("0151 — fachliche Gleichwertigkeit in vier Stufen", () => {
  it("Stufe 1 prüft Bauart und Spaltentypen", () => {
    expect(migration151).toContain("format_type(a.atttypid, a.atttypmod)");
    expect(migration151).toContain("'sky_id text, cheapest_cents integer'");
  });

  it("Stufe 2 liest die Herkunft aus pg_depend, nicht aus dem Text", () => {
    /* Eine Sicht hält ihre Abhängigkeiten in der Umschreiberegel. Aus dem
       Katalog gelesen ist die Prüfung formatunabhängig — und sie fängt eine
       Fassung, die `offer_state` oder `shop_inventory` direkt liest. */
    expect(migration151).toContain("'pg_rewrite'::regclass");
    expect(migration151).toContain("d.refclassid = 'pg_class'::regclass");
    expect(migration151).toContain("Relation(en) direkt");
    expect(migration151).toContain("position('shop_offers' in v_t)");
    expect(migration151).toContain("position('v1_sale_condition' in v_t)");
  });

  it("Stufe 3 prüft jedes tragende Stück des normalisierten Wortlauts", () => {
    /* `min(round(` fängt ein `max`, `available` einen fehlenden Filter —
       beides lässt Spalten und Herkunft unverändert. */
    expect(migration151).toContain("pg_get_viewdef");
    for (const stueck of ["'shop_offers'", "'v1_sale_condition'", "'min(round('",
                          "'*100'", "'available'", "'groupby'"]) {
      expect(migration151, stueck).toContain(stueck);
    }
  });

  it("Stufe 4 vergleicht das Verhalten — in EINER Anweisung", () => {
    /*
     * Zwei getrennte Abfragen bekämen unter READ COMMITTED zwei
     * Schnappschüsse, und ein gleichzeitiger Kauf zwischen ihnen wäre ein
     * Fehlalarm. `shop_offers()` ist `stable`, also sehen beide
     * Unterabfragen innerhalb einer Anweisung dieselben Daten.
     */
    const a = migration151.indexOf("into v_ist, v_soll");
    expect(a, "der Doppelabdruck fehlt").toBeGreaterThan(-1);
    expect(migration151).toContain("ein anderes Ergebnis");
    expect(migration151).toContain("nicht ueberschrieben");
  });

  it("und ein Clientrecht auf der Sicht führt zum Abbruch", () => {
    expect(migration151).toContain("Clientrecht(e)");
    expect(migration151).toContain("revoke all on public.offer_state_live from public, anon, authenticated");
  });
});

