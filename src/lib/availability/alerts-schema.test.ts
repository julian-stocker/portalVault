describe("0150 — die Tabelle", () => {
  it("trägt genau die sieben vereinbarten Spalten, in dieser Folge", () => {
    /* Die Folge steht auch in der Nachbedingung der Migration und in der
       Nachkontrolle (101). Hier wird sie ein drittes Mal festgehalten —
       weil eine Spalte in der Mitte einzuschieben die billigste Art wäre,
       die beiden anderen Stellen stillschweigend falsch zu machen. */
    const a = migration.indexOf("create table public.availability_alerts (");
    const b = migration.indexOf("constraint availability_alerts_pk", a);
    const block = migration.slice(a, b);
    /* `\s+`, nicht `\s{2,}`: `notified_cents integer` ist die laengste
       Spalte und steht mit EINEM Leerzeichen da. Die erste Fassung dieses
       Tests zaehlte sie deshalb nicht mit und meldete sechs statt sieben. */
    const spalten = [...block.matchAll(/^  ([a-z_]+)\s+(bigint|uuid|text|timestamptz|integer)/gm)]
      .map((m) => m[1]);
    expect(spalten).toEqual(["id", "user_id", "sky_id", "created_at",
                             "notified_at", "notified_cents", "read_at"]);
  });

  it("id ist GENERATED ALWAYS, damit niemand einen Wert unterschiebt", () => {
    expect(migration).toContain("id             bigint      generated always as identity");
    expect(migration).not.toContain("generated by default as identity");
  });

  it("auth.users CASCADE und skylanders RESTRICT — DSGVO und kein Wegbrechen", () => {
    expect(migration).toMatch(
      /availability_alerts_user_fk[\s\S]{0,200}auth\.users[\s\S]{0,80}on delete\s+cascade/);
    expect(migration).toMatch(
      /availability_alerts_sky_fk[\s\S]{0,200}public\.skylanders[\s\S]{0,80}on delete\s+restrict/);
  });

  it("die drei CHECKs stehen, und der Preis darf 0 sein", () => {
    for (const c of ["availability_alerts_notified_price",
                     "availability_alerts_read_after_notified",
                     "availability_alerts_price_sane"]) {
      expect(migration, c).toContain(`constraint ${c}`);
    }
    /* `>= 0` und nicht `> 0`: `shop_price()` rundet auf zwei Stellen, und
       bei einem sehr kleinen Marktwert wird daraus 0.00. Ein `> 0` hätte den
       Abgleich an echten Daten abbrechen lassen (dieselbe Lehre wie 0146). */
    expect(migration).toContain("notified_cents is null or notified_cents >= 0");
    expect(migration).not.toMatch(/notified_cents\s*>\s*0\b/);
  });
});

