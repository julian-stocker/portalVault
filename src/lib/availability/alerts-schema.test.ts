/** Der Rumpf einer Funktion aus der Migration, zwischen `as $$` und `$$;`. */
function rumpf(signatur: string): string {
  const i = migration.indexOf(`create or replace function public.${signatur}`);
  expect(i, `${signatur} fehlt in der Migration`).toBeGreaterThan(-1);
  const a = migration.indexOf("as $$", i);
  const b = migration.indexOf("\n$$;", a);
  expect(b, `${signatur}: Rumpfende fehlt`).toBeGreaterThan(a);
  return migration.slice(a + "as $$".length, b);
}

