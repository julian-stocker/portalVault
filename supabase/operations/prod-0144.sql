comment on function public.system_platform_export() is
  'The database half of one complete platform backup as a single JSON document (0105, extended by 0144) — the archive file database.json. 54 sections in one statement, so every one of them comes from the same MVCC snapshot; money is rendered as text so no reader turns 7.85 into a float. The data object is assembled from six jsonb_build_object calls joined with ||, because PostgreSQL takes at most 100 arguments per call. The selection lives in src/lib/backup/platform-manifest.ts and is enforced from both sides by platform-sql.test.ts. Export, never synchronisation: it writes nothing, reads no auth table, and carries none of the legacy Excel import tables. 0144 added purchase_calculations (0142) and raised format_version to 2; archives of version 1 stay valid and simply carry 53 sections. There is still no restore — format_version is the contract that keeps one possible, and the limits are written down in supabase/checks/0144_restore_limits.md.';

-- ---------------------------------------------------------------------------
-- 3. Die Rechte, ausdruecklich festgeschrieben
--
-- `create or replace function` ERHAELT den bestehenden ACL — diese zwei
-- Zeilen aendern also nichts. Sie stehen hier, weil eine Datei, die eine
-- `security definer`-Funktion schreibt, ihre Rechte nennen soll: wer sie
-- liest, muss nicht in `0105` nachsehen, wem sie offensteht.
-- ---------------------------------------------------------------------------
revoke all on function public.system_platform_export() from public, anon;
grant execute on function public.system_platform_export() to authenticated;


-- ---------------------------------------------------------------------------
-- 4. Nachbedingungen
-- ---------------------------------------------------------------------------
do $nach$
declare
  v_abdruck   text;
  v_bereiche  integer;
  v_definer   boolean;
  v_volatil   "char";
  v_pfad      boolean;
  v_offen     integer;
  v_auth      integer;
  v_policies  integer;
begin
  select md5(p.prosrc),
         (length(p.prosrc) - length(replace(p.prosrc, 'coalesce((', ''))) / length('coalesce(('),
         p.prosecdef, p.provolatile,
         /*
          * AUSGEPACKT, NICHT VERGLICHEN. PostgreSQL quotiert den Wert:
          * `set search_path = ''` liegt als `search_path=""` ab. Ein
          * Vergleich gegen ein Literal waere ein Fehlalarm in
          * Wartestellung, und `_` ist in `like` ein Platzhalter — deshalb
          * `search\_path` mit Escape.
          * `src/lib/admin/migration-integrity.test.ts` haelt diese Regel
          * fuer jede Datei fest, die `proconfig` liest.
          */
         (select count(*) = 1 from unnest(coalesce(p.proconfig, '{}')) c
           where c like 'search\_path=%')
    into v_abdruck, v_bereiche, v_definer, v_volatil, v_pfad
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'system_platform_export';

  if v_abdruck <> '4c4d2e7c81e4efa8e18cdffa06bba40a' then
    raise exception '0144 Nachbedingung: Rumpfabdruck ist % und nicht %',
      v_abdruck, '4c4d2e7c81e4efa8e18cdffa06bba40a';
  end if;
  if v_bereiche <> 54 then
    raise exception '0144 Nachbedingung: % Bereiche statt 54', v_bereiche;
  end if;
  if not v_definer or v_volatil <> 's' or not v_pfad then
    raise exception '0144 Nachbedingung: Attribute verloren — definer %, '
      'volatility %, genau eine search_path-Festlegung %',
      v_definer, v_volatil, v_pfad;
  end if;

  -- Der neue Bereich steht drin, und die Formatversion ist zwei.
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                  where n.nspname = 'public' and p.proname = 'system_platform_export'
                    and p.prosrc like '%''purchase_calculations'', coalesce((%') then
    raise exception '0144 Nachbedingung: der Bereich purchase_calculations fehlt';
  end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                  where n.nspname = 'public' and p.proname = 'system_platform_export'
                    and p.prosrc like '%''format_version'', 2,%') then
    raise exception '0144 Nachbedingung: format_version ist nicht 2';
  end if;

  -- Die Rechte: niemand ausser `authenticated`.
  select count(*) into v_offen
    from pg_proc p, aclexplode(p.proacl) a
   where p.oid = to_regprocedure('public.system_platform_export()')
     and a.privilege_type = 'EXECUTE'
     and (a.grantee = 0 or a.grantee::regrole::text in ('anon', 'public'));
  if v_offen <> 0 then
    raise exception '0144 Nachbedingung: % offene EXECUTE-Rechte', v_offen;
  end if;
  select count(*) into v_auth
    from pg_proc p, aclexplode(p.proacl) a
   where p.oid = to_regprocedure('public.system_platform_export()')
     and a.privilege_type = 'EXECUTE'
     and a.grantee::regrole::text = 'authenticated';
  if v_auth <> 1 then
    raise exception '0144 Nachbedingung: authenticated darf nicht ausfuehren';
  end if;

  -- Und die Tabelle selbst ist unberuehrt: RLS an, vier Richtlinien.
  select count(*) into v_policies from pg_policies
   where schemaname = 'public' and tablename = 'purchase_calculations';
  if v_policies <> 4 then
    raise exception '0144 Nachbedingung: purchase_calculations hat % Richtlinien '
      'statt vier — diese Migration haette sie nicht anfassen duerfen', v_policies;
  end if;
  if not (select relrowsecurity from pg_class
           where oid = 'public.purchase_calculations'::regclass) then
    raise exception '0144 Nachbedingung: RLS auf purchase_calculations ist aus';
  end if;

  raise notice '0144: Rumpf %, 54 Bereiche, format_version 2, Rechte unveraendert, '
    'purchase_calculations mit 4 Richtlinien unberuehrt', v_abdruck;
end
