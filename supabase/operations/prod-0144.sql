    raise exception '0144 Abbruch: der vorhandene Rumpf ist % und nicht der '
      'aus 0105 (2e2da90e976a1e73ca00aba7cd830fae). Diese Migration ist aus genau '
      'jener Fassung gerechnet; eine andere wird nicht blind ueberschrieben.',
