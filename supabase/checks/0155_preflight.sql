--   101-104  DIE GRUNDLAGE, und die wichtigste ist `0154`:
--            `admin_merge_references()` MUSS stehen, denn `0155` benutzt sie
--            fuer die Referenzpruefung. Es soll sie genau einmal geben.
--   111      DASS ES `admin_discard_draft` noch nicht gibt.
--   121-124  DER BESTAND, den `0155` nicht anfasst — und die Zahlen, an denen
--            sich ablesen laesst, WAS die Funktion spaeter ueberhaupt treffen
--            koennte: Entwuerfe, davon mit `source = admin`, und die
--            Adminzeilen, die KEINE Entwuerfe sind.
